import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const sources = {
  QQQI: 'https://neosfunds.com/qqqi/',
  SPYI: 'https://neosfunds.com/spyi/',
  IWMI: 'https://neosfunds.com/iwmi/',
  QQQH: 'https://neosfunds.com/qqqh/',
  BTCI: 'https://neosfunds.com/btci/',
};

const parseArray = (html, name) => {
  const match = html.match(new RegExp(`(?:const|let|var)\\s+${name}\\s*=\\s*(\\[[^;]+\\])`));
  if (!match) throw new Error(`Missing ${name}`);
  return JSON.parse(match[1]);
};

const snapshots = {};
for (const [ticker, url] of Object.entries(sources)) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${ticker}: ${response.status}`);
  const html = await response.text();
  const dates = parseArray(html, 'dates');
  const values = parseArray(html, 'navValues');
  if (dates.length !== values.length || dates.length < 2) throw new Error(`${ticker}: invalid NAV series`);
  snapshots[ticker] = {
    ticker,
    currency: 'USD',
    seriesType: 'nav-total-return-index',
    source: url,
    dataAsOf: dates.at(-1),
    points: dates.map((date, index) => [date, values[index]]),
  };
}

const publicDir = path.join(root, 'public/data/nav');
await fs.mkdir(publicDir, { recursive: true });
for (const [ticker, snapshot] of Object.entries(snapshots)) {
  await fs.writeFile(path.join(publicDir, `${ticker}.json`), `${JSON.stringify(snapshot)}\n`);
}

const header = `// Generated by scripts/update-nav-data.mjs from each fund issuer's NAV performance page.\nexport type NavPoint = [string, number];\nexport type NavSnapshot = { ticker: string; currency: string; seriesType: 'nav-total-return-index'; source: string; dataAsOf: string; points: NavPoint[] };\n\n`;
const body = `export const navSnapshots: Record<string, NavSnapshot> = ${JSON.stringify(snapshots, null, 2)};\n`;
await fs.writeFile(path.join(root, 'src/data/nav.ts'), header + body);
console.log(`Updated ${Object.keys(snapshots).length} issuer NAV series.`);
